-- Polka · РАЗОВАЯ чистка тестовых/пустых полок из shelves (+ тест-строка справочника).
-- Anon-ключ к shelves не имеет доступа на удаление (RLS), поэтому чистим здесь, service-role.
-- БЕЗОПАСНО удаляем:
--   • полки с ПУСТЫМ именем (проверено — все без книг);
--   • тест-маркеры, чьё имя начинается на «__» (__deleted_test__, __foot3__, __foot_test__);
--   • полку «Тестер» — она из прошлой сессии, её тест-цитаты («ц» на «Мартин Иден» и т.п.)
--     всплывали в «Цитатах читателей» на страницах книг.
-- Реальные полки (Ольга, Дарья, keymari, nanorè., Veronica, нюк и др.) НЕ трогаются.
-- Выполни в Supabase → SQL Editor. Сначала шаг 1 (посмотреть), потом шаг 2 (удалить).

-- 1) ПРЕДПРОСМОТР — что удалится (ожидаем только "", __…__ и «Тестер»):
select code, name, length(coalesce(data,'')) as data_len
from shelves
where name = '' or name ~ '^__' or name = 'Тестер'
order by name;

-- 2) УДАЛЕНИЕ тестовых/пустых полок:
delete from shelves
where name = '' or name ~ '^__' or name = 'Тестер';

-- 3) Тест-строка эталон-самопроверки в справочнике (не влияет на пользователей, но приберём):
delete from book_catalog where norm = '__cover_ref_selftest__';

-- 4) Очистить АВТО-ЗАГРЯЗНЕНИЕ справочника для «Мартин Иден»:
--    Google по названию подсунул учебное пособие Р.Орловой «"Мартин Иден" Джека Лондона»,
--    и авто-запись сохранила его автора/обложку/описание. Чистим (эталон cover_ref не трогаем).
--    После этого автор возьмётся с книги (Джек Лондон), обложку задашь эталоном через ✏️.
update book_catalog set cover='', author='', description='' where norm='мартин иден';

